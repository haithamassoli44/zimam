import { describe, expect, it } from 'vitest'

import { badPatterns, generatedRules, generatedText } from '@/lib/generated'

describe('generated files', () => {
  it('knows GitHub’s own paths, like lockfiles and minified files', () => {
    const isGenerated = generatedRules(null, [])
    expect(isGenerated('pnpm-lock.yaml')).toBe(true)
    expect(isGenerated('web/dist/app.min.js')).toBe(true)
    expect(isGenerated('src/app.ts')).toBeNull()
  })

  it('takes the repository’s .gitattributes first, the last line that matches deciding', () => {
    const isGenerated = generatedRules('docs/** linguist-generated\ndocs/guide.md -linguist-generated\n', [])
    expect(isGenerated('docs/api/index.md')).toBe(true)
    expect(isGenerated('docs/guide.md')).toBe(false)
    expect(generatedRules('pnpm-lock.yaml linguist-generated=false', [])('pnpm-lock.yaml')).toBe(false)
  })

  it('takes the patterns from Settings, as Git matches them', () => {
    const isGenerated = generatedRules(null, ['schema/*.json', '/build/', '*.snap', '# a note', ''])
    expect(isGenerated('schema/api.json')).toBe(true)
    expect(isGenerated('schema/deep/api.json')).toBeNull()
    expect(isGenerated('build/out.js')).toBe(true)
    expect(isGenerated('src/build/out.js')).toBeNull()
    expect(isGenerated('test/__snapshots__/a.test.ts.snap')).toBe(true)
  })

  it('reads a generator’s mark, or a minified look, in the text', () => {
    expect(generatedText('api/types.ts', '// Code generated by openapi. DO NOT EDIT.\nexport type A = 1\n')).toBe(true)
    expect(generatedText('src/app.ts', 'export const a = 1\n')).toBe(false)
    expect(generatedText('vendor/lib.js', `${'x'.repeat(500)}\n${'y'.repeat(500)}\n`)).toBe(true)
  })

  it('skips a pattern no test can be made of, and still reads the rest', () => {
    const isGenerated = generatedRules(null, ['[z-a]', 'a[\\]b', 'gen/**'])
    expect(isGenerated('z')).toBeNull()
    expect(isGenerated('gen/api.ts')).toBe(true)
    expect(badPatterns(['[z-a]', 'gen/**', '# a comment', ' ', 'a[\\]b'])).toEqual(['[z-a]', 'a[\\]b'])
  })

  it('reads only the linguist-generated lines of a .gitattributes, so one it can’t read about something else changes nothing', () => {
    const attributes = '[z-a] text\n*.png binary\nbad[\\]/** linguist-generated\nproto/** linguist-generated\n'
    const isGenerated = generatedRules(attributes, [])
    expect(isGenerated('proto/api.pb.go')).toBe(true)
    expect(isGenerated('src/app.ts')).toBeNull()
  })
})
