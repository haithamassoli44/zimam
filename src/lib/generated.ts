// Which changed files are generated, and so hidden from the diff and the file tree.
//
// GitHub's API doesn't say. GitHub's own diff folds what Linguist calls generated, plus what a repository marks with
// `linguist-generated` in .gitattributes. Zimam follows both, and adds patterns the reader sets in Settings.

// The path rules of Linguist's generated.rb that come up in pull requests.
const GITHUB_PATHS: RegExp[] = [
  // Lockfiles
  /(^|\/)(package-lock|npm-shrinkwrap)\.json$/,
  /(^|\/)pnpm-lock\.yaml$/,
  /(^|\/)yarn\.lock$/,
  /(^|\/)bun\.lockb?$/,
  /(^|\/)deno\.lock$/,
  /(^|\/)composer\.lock$/,
  /(^|\/)Cargo\.lock$/,
  /(^|\/)Gemfile\.lock$/,
  /(^|\/)(Pipfile|poetry|pdm|uv|pixi)\.lock$/,
  /(^|\/)flake\.lock$/,
  /(^|\/)MODULE\.bazel\.lock$/,
  /(^|\/)go\.(sum|work\.sum)$/,
  /(^|\/)Package\.resolved$/,
  /(^|\/)pubspec\.lock$/,
  /(^|\/)packages\.lock\.json$/,
  /(^|\/)gradle\.lockfile$/,
  // Minified files and source maps
  /\.min\.(js|css|mjs)$/,
  /\.(js|css|mjs)\.map$/,
  // Protocol buffers, Thrift and friends
  /\.pb\.(go|cc|h|swift)$/,
  /_pb2(_grpc)?\.pyi?$/,
  /_pb\.(js|d\.ts)$/,
  /(^|\/)gen-(cpp|java|py|rb|js|go)\//,
  // .NET designer files, SpecFlow
  /\.designer\.(cs|vb)$/,
  /\.feature\.cs$/,
  // Xcode and CocoaPods
  /\.(nib|xcworkspacedata|xcuserstate)$/,
  /(^|\/)Pods\//,
  /(^|\/)Carthage\/Build\//,
  // Wrappers
  /(^|\/)gradlew(\.bat)?$/,
  /(^|\/)gradle\/wrapper\//,
  /(^|\/)mvnw(\.cmd)?$/,
  // Unity
  /\.meta$/,
  // Dependencies checked in
  /(^|\/)node_modules\//,
  // R documentation
  /(^|\/)man\/[^/]+\.Rd$/,
]

// Linguist also reads the first lines of a file for a generator's mark.
const GITHUB_MARKS = [
  /Code generated .* DO NOT EDIT\.?/,
  /@generated\b/,
  /^\s*(\/\/|#|\/\*|<!--)\s*(This file (is|was) (automatically |auto-)?generated|Generated by )/im,
  /Generated by Cython/,
  /\bAUTOGENERATED FILE\b/i,
]

const isPattern = (line: string) => !!line.trim() && !line.trim().startsWith('#')

/**
 * Turns a .gitattributes or Settings pattern into a test of a path, the way Git matches them. Null for a line without
 * a pattern, and for a pattern no test can be made of, such as a range backwards like `[z-a]`: Git skips those too.
 */
function patternTest(pattern: string): RegExp | null {
  if (!isPattern(pattern)) return null
  let glob = pattern.trim()
  const anchored = glob.startsWith('/') || glob.slice(0, -1).includes('/')
  glob = glob.replace(/^\//, '')
  let source = ''
  for (let index = 0; index < glob.length; index++) {
    const char = glob[index]
    if (char === '*' && glob[index + 1] === '*') {
      const slash = glob[index + 2] === '/'
      source += slash ? '(?:.*/)?' : '.*'
      index += slash ? 2 : 1
    } else if (char === '*') source += '[^/]*'
    else if (char === '?') source += '[^/]'
    else if (char === '{') {
      const end = glob.indexOf('}', index)
      if (end < 0) source += '\\{'
      else {
        source += `(?:${glob
          .slice(index + 1, end)
          .split(',')
          .map((part) => part.replace(/[.+^$()|[\]\\]/g, '\\$&').replace(/\*/g, '[^/]*'))
          .join('|')})`
        index = end
      }
    } else if (char === '[') {
      const end = glob.indexOf(']', index)
      if (end < 0) source += '\\['
      else {
        source += glob.slice(index, end + 1).replace('[!', '[^')
        index = end
      }
    } else source += char.replace(/[.+^$()|\\]/g, '\\$&')
  }
  // A pattern for a folder takes everything in it.
  if (source.endsWith('/')) source += '.*'
  try {
    return new RegExp(`${anchored ? '^' : '(^|/)'}${source}(/.*)?$`)
  } catch {
    return null
  }
}

/** The Settings patterns no test can be made of, which count for nothing. */
export const badPatterns = (patterns: string[]) =>
  patterns.filter((pattern) => isPattern(pattern) && !patternTest(pattern))

interface Rule {
  test: RegExp
  generated: boolean
}

/**
 * The `linguist-generated` lines of a .gitattributes file. The last line that matches a path decides. Other lines aren't
 * read, so one this can't read, about something else, changes nothing.
 */
function attributeRules(text: string | null): Rule[] {
  const rules: Rule[] = []
  for (const line of (text ?? '').split('\n')) {
    const [pattern, ...attributes] = line.trim().split(/\s+/)
    const marks = attributes.flatMap((attribute) =>
      attribute === 'linguist-generated' || attribute === 'linguist-generated=true'
        ? [true]
        : attribute === '-linguist-generated' || attribute === 'linguist-generated=false'
          ? [false]
          : [],
    )
    const test = marks.length && pattern ? patternTest(pattern) : null
    if (test) for (const generated of marks) rules.push({ test, generated })
  }
  return rules
}

/**
 * Which files are generated by their paths: the repository's .gitattributes first, then the patterns in Settings, then
 * GitHub's own paths. Null for a path that doesn't tell, which a generator's mark in the file's text can then decide.
 */
export function generatedRules(attributes: string | null, patterns: string[]) {
  const rules = attributeRules(attributes)
  const custom = patterns.map(patternTest).filter((test) => test !== null)
  return (path: string): boolean | null => {
    const attribute = rules.findLast((rule) => rule.test.test(path))
    if (attribute) return attribute.generated
    if (custom.some((test) => test.test(path)) || GITHUB_PATHS.some((test) => test.test(path))) return true
    return null
  }
}

/**
 * Whether a file's text carries a generator's mark, or reads as minified: few lines, and long ones. Unlike the rules,
 * what a text says stays with it.
 */
export function generatedText(path: string, text: string): boolean {
  if (GITHUB_MARKS.some((mark) => mark.test(text.slice(0, 600)))) return true
  if (!/\.(js|css|mjs)$/.test(path)) return false
  const lines = text.split('\n', 30)
  const average = lines.reduce((sum, line) => sum + line.length, 0) / Math.max(lines.length, 1)
  return lines.length > 1 && average > 110
}
